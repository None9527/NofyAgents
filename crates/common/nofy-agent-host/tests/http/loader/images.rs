fn capture_definition() -> Value {
    let python=std::process::Command::new("/usr/bin/python3").args(["-I","-c","import sys,sysconfig,json; print(json.dumps({'stdlib':sysconfig.get_path('stdlib'),'version':str(sys.version_info.major)+'.'+str(sys.version_info.minor)}))"]).output().unwrap();
    assert!(python.status.success());
    let info: Value = serde_json::from_slice(&python.stdout).unwrap();
    let stdlib = PathBuf::from(info["stdlib"].as_str().unwrap());
    let version = info["version"].as_str().unwrap();
    let mut files = BTreeMap::new();
    files.insert(
        "bin/python".to_owned(),
        std::fs::canonicalize("/usr/bin/python3").unwrap(),
    );
    let mut pending = vec![stdlib.clone()];
    let mut binaries = vec![files["bin/python"].clone()];
    let mut excludes = Vec::new();
    while let Some(dir) = pending.pop() {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            let suffix = path.strip_prefix(&stdlib).unwrap();
            let meta = std::fs::symlink_metadata(&path).unwrap();
            if meta.is_dir() {
                let name = path.file_name().unwrap().to_str().unwrap();
                // Source remains complete; machine-generated bytecode caches
                // and CPython development-linker artifacts are not runtime inputs.
                if name == "__pycache__" || name.starts_with("config-") {
                    excludes.push(suffix.to_str().unwrap().to_owned());
                    continue;
                }
                pending.push(path);
                continue;
            }
            if meta.file_type().is_symlink() {
                excludes.push(suffix.to_str().unwrap().to_owned());
                let real = std::fs::canonicalize(&path).unwrap();
                if real.is_file() {
                    files.insert(format!("lib/python{version}/{}", suffix.display()), real);
                }
            }
            if path.extension().is_some_and(|s| s == "so") {
                binaries.push(path);
            }
        }
    }
    // Fixture diagnostics over trusted installed Python libraries only. The
    // production packager executes no source and requires explicit mappings.
    let mut libraries = BTreeMap::new();
    for binary in binaries {
        let output = std::process::Command::new("ldd")
            .arg(binary)
            .output()
            .unwrap();
        for line in String::from_utf8_lossy(&output.stdout).lines() {
            let words = line.split_whitespace().collect::<Vec<_>>();
            if words.len() >= 3 && words[1] == "=>" && words[2].starts_with('/') {
                libraries.insert(format!("lib/{}", words[0]), PathBuf::from(words[2]));
            } else if words.first().is_some_and(|s| s.starts_with('/')) {
                let source = PathBuf::from(words[0]);
                libraries.insert(
                    format!("lib/{}", source.file_name().unwrap().to_str().unwrap()),
                    source,
                );
            }
        }
    }
    files.extend(libraries);
    let loader = files
        .keys()
        .find(|p| p.contains("ld-linux-"))
        .unwrap()
        .clone();
    json!({"id":"locked-python","executable":"bin/python","loader":loader,"library_dirs":["lib"],"prefix_args":["-S","-s","-B"],"env":{"PYTHONHOME":{"kind":"path","path":"."}},"files":files,"trees":{format!("lib/python{version}"):{"path":stdlib,"exclude":excludes}}})
}
async fn image() -> RuntimeImage {
    tokio::task::spawn_blocking(|| {
        static IMAGE: std::sync::OnceLock<RuntimeImage> = std::sync::OnceLock::new();
        IMAGE
            .get_or_init(|| {
                RuntimeImage::capture(serde_json::from_value(capture_definition()).unwrap())
                    .unwrap()
            })
            .clone()
    })
    .await
    .unwrap()
}
fn system(image: &RuntimeImage, multiplier: i32) -> Value {
    let mut value = document(&Value::Null, json!({"bundle":package(multiplier)}));
    value["modules"][1]["factory"] = json!("resource.process_locked");
    value["modules"][1]["config"] = json!({"image":image.manifest.digest().unwrap()});
    value["modules"][2]["config"]["contract"]["timeout_ms"] = json!(60000);
    value
}
fn deployment(image: &RuntimeImage, multiplier: i32) -> Value {
    json!({"format":"nofy.deployment/v1","system":system(image,multiplier),"runtime_images":[image]})
}
#[tokio::test]
async fn prepared_image_manifests_are_rechecked_at_publication_and_direct_runtime_admission() {
    use nofy_agent_runtime::{
        supervisor::{RunSupervisor, jobs::ProgramSubmission},
        system::SystemFile,
    };
    let image = image().await;
    let dir = tempfile::tempdir().unwrap();
    let (kernel, server) = hosted(dir.path()).await;
    kernel.loader().images.put(image.clone()).unwrap();
    let resolved = kernel
        .loader()
        .resolve_file(serde_json::from_value(system(&image, 2)).unwrap())
        .await
        .unwrap();
    let source = match resolved {
        SystemFile::Source(source) => source,
        _ => panic!("expected source"),
    };
    let compiled = kernel.control().prepare(source).unwrap();
    let submission = ProgramSubmission::for_program(
        compiled.program("compute").unwrap(),
        "stale-image",
        "stale-image",
        None,
    )
    .unwrap();
    let object = dir
        .path()
        .join("loader/images/objects")
        .join(format!("{}.json", image.manifest.digest().unwrap()));
    let backup = dir.path().join("image-backup.json");
    std::fs::rename(&object, &backup).unwrap();
    assert!(
        kernel
            .control()
            .install_file(SystemFile::Locked(compiled.bundle.clone()))
            .await
            .is_err()
    );
    let supervisor = RunSupervisor::new(kernel.store().clone());
    assert!(supervisor.submit_program(submission.clone()).await.is_err());
    assert!(
        kernel
            .store()
            .execution_job("stale-image")
            .await
            .unwrap()
            .is_none()
    );
    std::fs::rename(backup, object).unwrap();
    kernel
        .control()
        .install_file(SystemFile::Locked(compiled.bundle.clone()))
        .await
        .unwrap();
    supervisor.submit_program(submission).await.unwrap();
    let result = supervisor
        .execute_submitted(compiled.registry(), "stale-image")
        .await
        .unwrap();
    let Some(nofy_agent_runtime::RunOutcome::Completed { output, .. }) = result else {
        panic!("unexpected execution: {result:?}");
    };
    let decoded: Value = serde_json::from_str(&output).unwrap();
    assert_eq!(decoded.get("value").unwrap_or(&decoded)["result"], 2);
    assert_eq!(
        request(
            &server,
            reqwest::Method::GET,
            "/api/v1/catalog",
            VIEW,
            Value::Null
        )
        .await
        .0,
        200
    );
}
async fn hosted(path: &Path) -> (KernelHost, Serving) {
    let kernel = host(path, Arc::new(AtomicUsize::new(0))).await;
    let server = serve(kernel.router()).await;
    (kernel, server)
}
async fn settled(server: &Serving, id: &str) -> Value {
    tokio::time::timeout(Duration::from_secs(60), async {
        loop {
            let (status, value) = request(
                server,
                reqwest::Method::GET,
                &format!("/api/v1/runs/{id}"),
                ADMIN,
                Value::Null,
            )
            .await;
            assert_eq!(status, 200, "{value}");
            if !value["execution"].is_null() && value["execution"]["status"] != "running" {
                return value;
            }
            tokio::time::sleep(Duration::from_millis(30)).await;
        }
    })
    .await
    .unwrap()
}
#[tokio::test]
async fn locked_image_preflight_is_pure_and_portable_deployment_runs_without_local_runtime_install()
{
    let _serial = IMAGE_RUNS.lock().await;
    let image = image().await;
    let dir = tempfile::tempdir().unwrap();
    let (kernel, server) = hosted(dir.path()).await;
    let file = deployment(&image, 2);
    assert_eq!(
        request(
            &server,
            reqwest::Method::POST,
            "/api/v1/runtime-images",
            VIEW,
            json!(&image)
        )
        .await
        .0,
        403
    );
    assert_eq!(
        request(
            &server,
            reqwest::Method::POST,
            "/api/v1/import",
            PUBLISH,
            file.clone()
        )
        .await
        .0,
        403
    );
    let preview = post(&server, "/api/v1/validate", file.clone()).await;
    assert!(preview["document"]["modules"][1]["config"]["manifest"]["files"].is_object());
    for path in ["objects", "trees"] {
        assert_eq!(
            std::fs::read_dir(dir.path().join("loader/images").join(path))
                .unwrap()
                .count(),
            0
        );
    }
    assert!(
        request(
            &server,
            reqwest::Method::POST,
            "/api/v1/validate",
            ADMIN,
            system(&image, 2)
        )
        .await
        .0 >= 400
    );
    let imported = post(&server, "/api/v1/import", file).await;
    let release = imported["bundle"]["digest"].as_str().unwrap();
    assert_eq!(preview["digest"], release);
    assert!(!imported["bundle"].to_string().contains("blobs"));
    assert_eq!(
        request(
            &server,
            reqwest::Method::GET,
            &format!("/api/v1/releases/{release}/deployment"),
            VIEW,
            Value::Null,
        )
        .await
        .0,
        503,
        "missing origin must not fall back to embedding dependencies"
    );
    let repository = crate::dependencies::Repository::new(kernel.loader()).await;
    kernel
        .loader()
        .acquire_image(
            serde_json::from_value(repository.requirement(&image)["source"].clone()).unwrap(),
            Default::default(),
        )
        .await
        .unwrap();
    let stop = CancellationToken::new();
    let signal = stop.clone();
    let worker_kernel = kernel.clone();
    let worker = tokio::spawn(async move { worker_kernel.run_worker(signal, 1).await.unwrap() });
    post(&server, "/api/v1/runs", run(release, "image-root")).await;
    let result = settled(&server, "image-root").await;
    assert_eq!(output(&result)["result"], 14, "{result}");
    let exported = request(
        &server,
        reqwest::Method::GET,
        &format!("/api/v1/releases/{release}/deployment"),
        VIEW,
        Value::Null,
    )
    .await;
    assert_eq!(exported.0, 200);
    assert_eq!(exported.1["format"], "nofy.deployment/v2");
    assert!(exported.1.get("runtime_images").is_none());
    assert_eq!(exported.1["runtime_sources"].as_array().unwrap().len(), 1);
    let fresh = tempfile::tempdir().unwrap();
    let target_loader = nofy_agent_host::loader::Loader::open(fresh.path()).unwrap();
    repository.authorize(&target_loader);
    assert!(
        target_loader
            .images
            .get(&image.manifest.digest().unwrap())
            .is_err()
    );
    drop(target_loader);
    let source = fresh.path().join("deployment.json");
    tokio::fs::write(&source, serde_json::to_vec(&exported.1).unwrap())
        .await
        .unwrap();
    let (other, mut child) = super::process::binary(fresh.path(), Some(&source)).await;
    assert_eq!(
        repository.requests(),
        2,
        "the actual CLI must reconstruct from the independent origin"
    );
    assert_eq!(
        request(
            &other,
            reqwest::Method::GET,
            "/api/v1/runtimes",
            ADMIN,
            Value::Null
        )
        .await
        .1,
        json!([])
    );
    let active = request(
        &other,
        reqwest::Method::GET,
        "/api/v1/systems/artifact-system/active",
        ADMIN,
        Value::Null,
    )
    .await
    .1;
    assert_eq!(active["release"], release);
    post(&other, "/api/v1/runs", run(release, "only-deployment")).await;
    assert_eq!(
        output(&settled(&other, "only-deployment").await)["result"],
        14
    );
    child.kill().await.unwrap();
    stop.cancel();
    worker.await.unwrap();
}

#[tokio::test]
async fn bundled_linker_and_environment_never_read_host_libraries_or_run_before_isolation() {
    let _serial = IMAGE_RUNS.lock().await;
    let mut image = image().await;
    let dir = tempfile::tempdir().unwrap();
    let preload = dir.path().join("probe.so");
    let marker = dir.path().join("pre-isolation-execution");
    let code = format!(
        "#include <fcntl.h>\n#include <unistd.h>\n__attribute__((constructor)) static void probe(void){{int fd=open({},O_WRONLY|O_CREAT|O_TRUNC,0600);if(fd>=0){{write(fd,\"ran\",3);close(fd);}}}}",
        serde_json::to_string(marker.to_str().unwrap()).unwrap()
    );
    let mut compiler = std::process::Command::new("cc")
        .args(["-shared", "-fPIC", "-x", "c", "-"])
        .arg("-o")
        .arg(&preload)
        .stdin(std::process::Stdio::piped())
        .spawn()
        .unwrap();
    use std::io::Write;
    compiler
        .stdin
        .take()
        .unwrap()
        .write_all(code.as_bytes())
        .unwrap();
    assert!(compiler.wait().unwrap().success());
    assert!(
        std::process::Command::new("/usr/bin/true")
            .env_clear()
            .env("LD_PRELOAD", &preload)
            .status()
            .unwrap()
            .success()
    );
    assert_eq!(std::fs::read(&marker).unwrap(), b"ran");
    std::fs::remove_file(&marker).unwrap();
    image.manifest.env.insert(
        "LD_PRELOAD".into(),
        serde_json::from_value(json!({"kind":"literal","value":preload})).unwrap(),
    );
    let (kernel, server) = hosted(dir.path()).await;
    let mut file = deployment(&image, 2);
    file["system"]["modules"][0]["config"]["bundle"]["files"] = json!({"main.py":r#"import os,sys,json,ctypes,hashlib,sqlite3,decimal
json.load(sys.stdin)
class Info(ctypes.Structure):
    _fields_=[('name',ctypes.c_char_p),('base',ctypes.c_void_p),('symbol',ctypes.c_char_p),('address',ctypes.c_void_p)]
lib=ctypes.CDLL('libc.so.6')
info=Info()
assert lib.dladdr(ctypes.cast(lib.gnu_get_libc_version,ctypes.c_void_p),ctypes.byref(info))!=0
try:
    open('/usr/lib/x86_64-linux-gnu/libc.so.6','rb').read(1)
    denied=False
except PermissionError:
    denied=True
print(json.dumps({'library':info.name.decode(),'host_denied':denied,'hash':hashlib.sha256(b'locked').hexdigest(),'decimal':str(decimal.Decimal('1.25')*2),'sqlite':sqlite3.connect(':memory:').execute('select 7').fetchone()[0]}))
"#});
    let imported = post(&server, "/api/v1/import", file).await;
    let release = imported["bundle"]["digest"].as_str().unwrap();
    let stop = CancellationToken::new();
    let signal = stop.clone();
    let worker = tokio::spawn(async move { kernel.run_worker(signal, 1).await.unwrap() });
    post(&server, "/api/v1/runs", run(release, "closed-environment")).await;
    let result = settled(&server, "closed-environment").await;
    let out = output(&result);
    assert_eq!(out["host_denied"], true, "{out}");
    assert!(
        out["library"]
            .as_str()
            .unwrap()
            .contains("/loader/images/trees/"),
        "{out}"
    );
    assert_eq!(out["sqlite"], 7);
    assert_eq!(out["decimal"], "2.50");
    assert!(out["library"].as_str().unwrap().ends_with("/lib/libc.so.6"));
    assert!(!marker.exists());
    stop.cancel();
    worker.await.unwrap();
}

#[tokio::test]
async fn packaging_cli_uses_explicit_definition_and_refuses_overwriting_output() {
    let _serial = IMAGE_RUNS.lock().await;
    let definition = tokio::task::spawn_blocking(capture_definition)
        .await
        .unwrap();
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("definition.json");
    let target = dir.path().join("image.json");
    tokio::fs::write(&source, serde_json::to_vec(&definition).unwrap())
        .await
        .unwrap();
    let path = source.clone();
    let output = target.clone();
    let result = tokio::task::spawn_blocking(move || {
        std::process::Command::new(env!("CARGO_BIN_EXE_nofy-runtime-image"))
            .arg("--definition")
            .arg(path)
            .arg("--output")
            .arg(output)
            .output()
            .unwrap()
    })
    .await
    .unwrap();
    assert!(
        result.status.success(),
        "{}",
        String::from_utf8_lossy(&result.stderr)
    );
    let captured: RuntimeImage =
        serde_json::from_slice(&tokio::fs::read(&target).await.unwrap()).unwrap();
    captured.validate().unwrap();
    assert_eq!(
        captured.manifest.digest().unwrap(),
        image().await.manifest.digest().unwrap()
    );
    let duplicate = tokio::task::spawn_blocking(move || {
        std::process::Command::new(env!("CARGO_BIN_EXE_nofy-runtime-image"))
            .arg("--definition")
            .arg(source)
            .arg("--output")
            .arg(target)
            .output()
            .unwrap()
    })
    .await
    .unwrap();
    assert!(!duplicate.status.success());
}

fn versioned(mut image: RuntimeImage, factor: i32) -> RuntimeImage {
    use base64::Engine;
    use std::io::Write;
    let directory = image
        .manifest
        .files
        .keys()
        .find_map(|name| name.strip_suffix("/os.py"))
        .unwrap()
        .to_owned();
    let bytes = format!("FACTOR={factor}\n").into_bytes();
    let digest = format!("{:x}", Sha256::digest(&bytes));
    let mut gzip = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
    gzip.write_all(&bytes).unwrap();
    image.blobs.insert(
        digest.clone(),
        base64::engine::general_purpose::STANDARD.encode(gzip.finish().unwrap()),
    );
    image.manifest.files.insert(
        format!("{directory}/nofy_image_version.py"),
        serde_json::from_value(json!({"digest":digest,"size":bytes.len(),"executable":false}))
            .unwrap(),
    );
    image.validate().unwrap();
    image
}
#[tokio::test]
async fn shipped_binary_selects_new_dependency_images_in_same_pid_and_keeps_old_release() {
    let _serial = IMAGE_RUNS.lock().await;
    let original = image().await;
    let dir = tempfile::tempdir().unwrap();
    let (server, mut child) = super::process::binary(dir.path(), None).await;
    let pid = child.id().unwrap();
    let mut releases = Vec::new();
    for (name, factor) in [("one", 2), ("two", 3)] {
        let image = versioned(original.clone(), factor);
        let installed = post(&server, "/api/v1/runtime-images", json!(&image)).await;
        assert_eq!(installed["digest"], image.manifest.digest().unwrap());
        let mut file = system(&image, 2);
        file["modules"][0]["config"]["bundle"]["files"] = json!({"main.py":"import json,sys,os\nfrom nofy_image_version import FACTOR\nprint(json.dumps({'result':json.load(sys.stdin)['n']*FACTOR,'secret_inherited':'NOFY_SECRET_MODEL_TOKEN' in os.environ}))\n"});
        let imported = post(&server, "/api/v1/import", file).await;
        let release = imported["bundle"]["digest"].as_str().unwrap().to_owned();
        post(&server, "/api/v1/runs", run(&release, name)).await;
        let result = settled(&server, name).await;
        assert_eq!(output(&result)["result"], 7 * factor, "{result}");
        assert_eq!(output(&result)["secret_inherited"], false);
        assert_eq!(child.id(), Some(pid));
        assert!(child.try_wait().unwrap().is_none());
        releases.push(release);
    }
    post(&server, "/api/v1/runs", run(&releases[0], "old-image")).await;
    assert_eq!(output(&settled(&server, "old-image").await)["result"], 14);
    post(&server, "/api/v1/runs", run(&releases[0], "one")).await;
    assert_eq!(output(&settled(&server, "one").await)["result"], 14);
    let listed = request(
        &server,
        reqwest::Method::GET,
        "/api/v1/runtime-images?limit=1",
        ADMIN,
        Value::Null,
    )
    .await;
    assert_eq!(listed.0, 200);
    assert_eq!(listed.1.as_array().unwrap().len(), 1);
    assert!(listed.1[0].get("blobs").is_none());
    let next = request(
        &server,
        reqwest::Method::GET,
        &format!(
            "/api/v1/runtime-images?limit=1&after={}",
            listed.1[0]["digest"].as_str().unwrap()
        ),
        ADMIN,
        Value::Null,
    )
    .await;
    assert_eq!(next.1.as_array().unwrap().len(), 1);
    assert_eq!(
        request(
            &server,
            reqwest::Method::GET,
            "/api/v1/runtime-images?limit=0",
            ADMIN,
            Value::Null
        )
        .await
        .0,
        422
    );
    child.kill().await.unwrap();
}
