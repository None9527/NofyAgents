//! Schema-first codegen + SDK tiers (FR2.9 + FR14.3, OC-F27).
//!
//! The control-plane schema is the SINGLE source: Python and TS client
//! stubs are GENERATED from it (deterministic string output — same schema,
//! same stubs), and the conformance suite is the passing standard for any
//! backend (「conformance 套件为合格标准」).

/// One method in the schema.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MethodSchema {
    pub name: String,
    /// Parameter names (typed string params for the stub tier).
    pub params: Vec<String>,
}

/// Generate a Python client stub from the schema. Deterministic.
pub fn codegen_python(methods: &[MethodSchema]) -> String {
    let mut out = String::from("# generated by nofy-agility sdk codegen — do not edit\n");
    out.push_str("import json, subprocess\n\n");
    out.push_str("class NofyClient:\n");
    out.push_str("    def __init__(self, command):\n");
    out.push_str("        self._command = command\n\n");
    out.push_str("    def _call(self, method, params):\n");
    out.push_str("        request = json.dumps({\"method\": method, \"params\": params})\n");
    out.push_str("        proc = subprocess.run(self._command, input=request, capture_output=True, text=True)\n");
    out.push_str("        return json.loads(proc.stdout)\n\n");
    for method in methods {
        let params = if method.params.is_empty() {
            "self".to_string()
        } else {
            format!("self, {}", method.params.join(", "))
        };
        let args = if method.params.is_empty() {
            "{}".to_string()
        } else {
            let entries: Vec<String> = method
                .params
                .iter()
                .map(|p| format!("\"{p}\": {p}"))
                .collect();
            format!("{{{}}}", entries.join(", "))
        };
        out.push_str(&format!(
            "    def {name}({params}):\n        return self._call(\"{name}\", {args})\n\n",
            name = method.name,
            params = params,
            args = args
        ));
    }
    out
}

/// Generate a TypeScript client stub from the schema. Deterministic.
pub fn codegen_typescript(methods: &[MethodSchema]) -> String {
    let mut out = String::from("// generated by nofy-agility sdk codegen — do not edit\n");
    out.push_str("export class NofyClient {\n");
    out.push_str(
        "  constructor(private call: (method: string, params: unknown) => Promise<unknown>) {}\n",
    );
    for method in methods {
        let params: Vec<String> = method
            .params
            .iter()
            .map(|p| format!("{p}: string"))
            .collect();
        let args = if method.params.is_empty() {
            "{}".to_string()
        } else {
            let entries: Vec<String> = method.params.iter().map(|p| format!("{p}")).collect();
            format!(
                "{{ {} }}",
                method
                    .params
                    .iter()
                    .zip(entries)
                    .map(|(p, _)| p.clone())
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        out.push_str(&format!(
            "  {name}({params}): Promise<unknown> {{ return this.call(\"{name}\", {args}); }}\n",
            name = method.name,
            params = params.join(", "),
            args = args
        ));
    }
    out.push_str("}\n");
    out
}

/// One conformance case: any backend must produce the expected shape.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConformanceCase {
    pub name: String,
    pub request_json: String,
    /// Required keys in the response.
    pub required_response_keys: Vec<String>,
}

/// The conformance suite (the passing standard).
pub fn conformance_suite() -> Vec<ConformanceCase> {
    vec![
        ConformanceCase {
            name: "hello-handshake".into(),
            request_json: r#"{"method":"hello","params":{}}"#.into(),
            required_response_keys: vec!["kind".into()],
        },
        ConformanceCase {
            name: "unknown-method-errors".into(),
            request_json: r#"{"method":"nope","params":{}}"#.into(),
            required_response_keys: vec!["error".into()],
        },
        ConformanceCase {
            name: "malformed-frame-rejected".into(),
            request_json: "{not a frame".into(),
            required_response_keys: vec!["error".into()],
        },
    ]
}

/// Check one response against a case.
pub fn check_conformance(case: &ConformanceCase, response_json: &str) -> bool {
    let Ok(value) = serde_json::from_str::<serde_json::Value>(response_json) else {
        return false;
    };
    case.required_response_keys
        .iter()
        .all(|key| value.get(key).is_some())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn schema() -> Vec<MethodSchema> {
        vec![
            MethodSchema {
                name: "search".into(),
                params: vec!["query".into()],
            },
            MethodSchema {
                name: "ping".into(),
                params: vec![],
            },
        ]
    }

    #[test]
    fn codegen_is_deterministic() {
        assert_eq!(codegen_python(&schema()), codegen_python(&schema()));
        assert_eq!(codegen_typescript(&schema()), codegen_typescript(&schema()));
    }

    #[test]
    fn python_stub_covers_every_method() {
        let stub = codegen_python(&schema());
        assert!(stub.contains("def search(self, query):"));
        assert!(stub.contains("def ping(self):"));
        assert!(stub.contains("\"search\""));
    }

    #[test]
    fn ts_stub_covers_every_method() {
        let stub = codegen_typescript(&schema());
        assert!(stub.contains("search(query: string)"));
        assert!(stub.contains("ping()"));
    }

    #[test]
    fn conformance_suite_checks_shapes() {
        let suite = conformance_suite();
        assert_eq!(suite.len(), 3);
        let hello = &suite[0];
        assert!(check_conformance(hello, r#"{"kind":"hello-ack"}"#));
        assert!(!check_conformance(hello, r#"{"other":1}"#));
        assert!(!check_conformance(hello, "not json"));
        let err_case = &suite[1];
        assert!(check_conformance(err_case, r#"{"error":{"code":1}}"#));
    }
}
