import WebSocket from 'ws';
const list = await (await fetch('http://127.0.0.1:9224/json/list')).json();
const page = list.find(p => p.type === 'page' && p.title === 'ZCode');
const ws = new WebSocket(page.webSocketDebuggerUrl, { perMessageDeflate: false });
let id = 0;
const send = (m, p={}) => ws.send(JSON.stringify({id:++id, method:m, params:p}));
ws.on('open', () => { send('Runtime.enable'); send('Log.enable'); });
ws.on('message', d => { const m = JSON.parse(d);
  if (m.method === 'Runtime.consoleAPICalled') console.log('[console]', m.params.type, m.params.args?.map(a=>a.value??a.description).join(' ').slice(0,300));
  if (m.method === 'Runtime.exceptionThrown') console.log('[exception]', JSON.stringify(m.params.exceptionDetails?.exception?.description||m.params.exceptionDetails?.text).slice(0,500));
  if (m.method === 'Log.entryAdded') console.log('[log]', m.params.entry.level, m.params.entry.text?.slice(0,300));
});
setTimeout(() => process.exit(0), 6000);
